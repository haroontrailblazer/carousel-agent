"""Free reference photos of the story's people, organisation and places.

When every picture found on the story's own pages was rejected, the cover
used to fall straight to a plain drawn background with the title on it. This
module is the free rung in between: Wikidata names the photo that illustrates
each subject (its P18 image, and the photo of an organisation's CEO, chair or
founder), and Wikimedia Commons serves that file under a free licence with an
author to credit.

No key and no billing: two public APIs over plain GETs, with a time budget.
Every file is checked before it is offered. AI-generated art, logos, flags,
maps, charts and screenshots are dropped, and so are files too small for a
1080x1350 cover and anything not on the licence allowlist (public domain,
CC BY, OGL; CC BY-SA only when ``settings.cover_allow_share_alike`` is on).
Nothing here raises: a failed lookup offers nothing.

The same Wikidata items also name each subject's official website (P856),
which tells the cover judge a company's own pages from fan sites
(:func:`official_sites`), and :func:`file_credit` credits a Wikimedia file
the cover found some other way.
"""
