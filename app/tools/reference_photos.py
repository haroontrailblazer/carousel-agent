def _is_name_word(word: str) -> bool:
    """Capitalised, CamelCase (OpenAI, iPhone) or an acronym, with 3 or more letters."""
    return (
        sum(ch.isalpha() for ch in word) >= 3
        and any(ch.isupper() for ch in word)
        and word.casefold() not in _STOPWORDS
    )


def _shouted(words: list[str]) -> set[int]:
    """Positions of words in an all-caps stretch ('AI MODELS RACE ON SPEED'): headline shouting, not acronyms."""
    caps = [bool(re.fullmatch(r"[A-Z][A-Z0-9]+", _POSSESSIVE_RE.sub("", w))) for w in words]
    out: set[int] = set()
    start = 0
    for index in range(len(words) + 1):
        if index < len(words) and caps[index]:
            continue
        if index - start >= _SHOUTED_RUN:
            out.update(range(start, index))
        start = index + 1
    return out


def _names_in(text: str, *, join: bool = True) -> list[str]:
    """Runs of name words in one piece of text: 'Prime Minister Anthony Albanese' -> 'Anthony Albanese'."""
    names: list[str] = []
    text = straight_quotes(str(text or "").translate(_DASHES))
    for chunk in _NAME_BREAK_RE.split(text):
        words = chunk.split()
        shouted = _shouted(words)
        run: list[str] = []
        for position, raw in enumerate(words):
            word_match = _WORD_RE.match(raw)
            word = word_match.group(0) if word_match and position not in shouted else ""
            possessive = bool(_POSSESSIVE_RE.search(raw))
            # A word glued to something else (GPT-5.4, DeepSeek-V3.2) ends the name.
            ends = not join or possessive or word != raw
            if run and join and word.isupper() and len(word) == 2:
                ends = True  # 'Mistral AI', 'Liquid AI': a short acronym only ends a name
            elif word and _is_name_word(word):
                if run and word.casefold() in _DEMONYMS:
                    names.append(" ".join(run))  # 'an OpenAI Australian government hack'
                    run = []
            else:
                if run:
                    names.append(" ".join(run))
                run = []
                continue
            run.append(word)
            if ends or len(run) >= _MAX_NAME_WORDS:
                names.append(" ".join(run))
                run = []
        if run:
            names.append(" ".join(run))
    return names


def _has_case_signal(text: str) -> bool:
    """False for an all-lowercase or shouting title: its capitals name nothing."""
    words = [w for w in re.findall(r"[A-Za-z]{2,}", text)]
    if not words or not any(ch.isupper() for ch in text):
        return False
    return sum(w.isupper() for w in words) * 2 <= len(words)


def _is_title_case(text: str) -> bool:
    words = [w for w in _WORD_RE.findall(text) if len(w) >= 4]
    return len(words) >= 3 and sum(w[0].isupper() for w in words) >= 0.7 * len(words)


def _prose(text: str) -> str:
    """Only the sentences of a text; a scraped page's menus and bylines are dropped."""
    lines = str(text or "").splitlines()
    return "\n".join(line for line in lines if len(line.split()) >= _MIN_PROSE_WORDS)


def story_subjects(
    news: Optional[dict],
    research: Optional[dict] = None,
    plan: Optional[dict] = None,
    *,
    limit: int = 4,
) -> list[str]:
    """The people, organisations, products and places the story names most.

    Read from the news title (unless it carries no capitals to go by), the
    news summary, the research summary and its first key facts, and the
    plan's hook and slide points; a name the hook repeats goes first, even
    when the hook is in capitals. Consecutive capitalised, CamelCase or
    acronym words form one name; months, weekdays, sentence starters and
    job titles are left out. A surname used alone ('Albanese said') counts
    toward the full name it shortens ('Anthony Albanese'). Ranked by how often
    each name appears; on a tie a person (a full name also used by its
    surname) comes first, then a multi-word name.
    """
    texts: list[tuple[str, bool]] = []  # (text, join words into names)
    news = news if isinstance(news, Mapping) else {}
    research = research if isinstance(research, Mapping) else {}
    plan = plan if isinstance(plan, Mapping) else {}
    title = str(news.get("title") or "")
    if _has_case_signal(title):
        texts.append((title, not _is_title_case(title)))
    texts.append((_prose(news.get("summary")), True))
    texts.append((str(research.get("summary") or ""), True))
    for fact in list(research.get("key_facts") or [])[:_FACTS_READ]:
        text = fact.get("fact") if isinstance(fact, Mapping) else fact
        texts.append((str(text or ""), True))
    hook = str(plan.get("hook_title") or "")
    if _has_case_signal(hook):
        texts.append((hook, not _is_title_case(hook)))
    for slide in list(plan.get("slides") or []):
        if isinstance(slide, Mapping):
            texts += [(str(point or ""), True) for point in slide.get("key_points") or []]

    counts: Counter[str] = Counter()
    first_seen: dict[str, int] = {}
    spelling: dict[str, str] = {}
    for text, join in texts:
        for name in _names_in(text, join=join):
            key = name.casefold()
            counts[key] += 1
            first_seen.setdefault(key, len(first_seen))
            spelling.setdefault(key, name)
    # 'Albanese' alone is the surname of 'Anthony Albanese': a Wikidata search
    # for the surname finds the family name, not the prime minister. Only a
    # full name written before the short one counts, the way news copy names
    # people: 'Australia' in the headline is not short for 'Services Australia'.
    people: set[str] = set()
    for key in [k for k in counts if " " not in k]:
        longer = [k for k in counts if k.endswith(f" {key}") and first_seen[k] < first_seen[key]]
        if longer:
            best = max(longer, key=lambda k: (counts[k], -first_seen[k]))
            counts[best] += counts.pop(key)
            people.add(best)
    # A nationality alone ('Australian') names no one to photograph.
    for key in [k for k in counts if k in _DEMONYMS]:
        counts.pop(key)
    # The cover's own hook says what the cover is about, even when it is
    # shouted ('XIAOMI CHARGES 10X MORE FOR FASTER AI' gives no names of its
    # own): a name found elsewhere whose words it repeats goes first.
    hook_words = {
        _POSSESSIVE_RE.sub("", _fold(word).strip(".,;:!?\"()"))
        for word in straight_quotes(hook).translate(_DASHES).replace("-", " ").split()
    }
    in_hook = {key for key in counts if all(_fold(word) in hook_words for word in key.split())}
    # On a tie a person goes first (a face makes the strongest cover), then
    # any multi-word name, then the name the story used first.
    ranked = sorted(
        counts,
        key=lambda k: (k not in in_hook, -counts[k], k not in people, " " not in k, first_seen[k]),
    )
    return [spelling[key] for key in ranked[: max(limit, 0)]]


